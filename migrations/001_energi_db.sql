BEGIN;

CREATE TABLE public.energi_db (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    meter_id integer NOT NULL,
    partial_ea double precision,
    tarif_t1 double precision,
    tarif_t2 double precision,
    voltage double precision,
    current_i1 double precision,
    current_i2 double precision,
    current_i3 double precision,
    waktu_jakarta timestamp without time zone
        GENERATED ALWAYS AS (created_at AT TIME ZONE 'Asia/Jakarta'::text) STORED
);

CREATE INDEX energi_db_waktu_jakarta_idx
    ON public.energi_db (waktu_jakarta);

CREATE INDEX energi_db_meter_waktu_jakarta_idx
    ON public.energi_db (meter_id, waktu_jakarta);

CREATE OR REPLACE FUNCTION public.get_energy_report(
    start_time timestamp with time zone,
    end_time timestamp with time zone
)
RETURNS TABLE (
    meter_id integer,
    delta_partial_ea double precision,
    delta_t1 double precision,
    delta_t2 double precision,
    biaya_lwbp double precision,
    biaya_wbp double precision,
    total_biaya double precision
)
LANGUAGE plpgsql
AS $function$
BEGIN
    RETURN QUERY
    WITH first_readings AS (
        SELECT DISTINCT ON (e.meter_id)
            e.meter_id, e.partial_ea, e.tarif_t1, e.tarif_t2
        FROM public.energi_db e
        WHERE e.waktu_jakarta >= (start_time AT TIME ZONE 'UTC')
            AND e.waktu_jakarta <= (end_time AT TIME ZONE 'UTC')
        ORDER BY e.meter_id, e.waktu_jakarta ASC
    ),
    last_readings AS (
        SELECT DISTINCT ON (e.meter_id)
            e.meter_id, e.partial_ea, e.tarif_t1, e.tarif_t2
        FROM public.energi_db e
        WHERE e.waktu_jakarta >= (start_time AT TIME ZONE 'UTC')
            AND e.waktu_jakarta <= (end_time AT TIME ZONE 'UTC')
        ORDER BY e.meter_id, e.waktu_jakarta DESC
    )
    SELECT
        f.meter_id,
        GREATEST(0::float8, l.partial_ea - f.partial_ea),
        GREATEST(0::float8, l.tarif_t1 - f.tarif_t1),
        GREATEST(0::float8, l.tarif_t2 - f.tarif_t2),
        GREATEST(0::float8, l.tarif_t1 - f.tarif_t1) * 1035.78,
        GREATEST(0::float8, l.tarif_t2 - f.tarif_t2) * 1553.67,
        GREATEST(0::float8, l.tarif_t1 - f.tarif_t1) * 1035.78
            + GREATEST(0::float8, l.tarif_t2 - f.tarif_t2) * 1553.67
    FROM first_readings f
    JOIN last_readings l ON f.meter_id = l.meter_id;
END;
$function$;

COMMIT;